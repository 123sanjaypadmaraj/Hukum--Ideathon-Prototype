// Writes the Zero Scan test-run inputs to test-files/ as real files, generated
// from js/scan/samples.js (Main Block of NHCE, with the six planted problems).
// Usage (from hukum-prototype/): node tools/make-test-files.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import * as SM from '../js/scan/samples.js';

const OUT = new URL('../test-files/', import.meta.url);
mkdirSync(OUT, { recursive: true });
const json = (v) => JSON.stringify(v, null, 2);
const FILES = [
  { key: 'solar', file: 'google-solar-buildingInsights.json', kind: 'json', make: () => json(SM.sampleSolarInsights()), what: 'Google Solar API roof segments and panel layout' },
  { key: 'openBuildings', file: 'open-buildings-footprint.csv', kind: 'text', make: () => SM.sampleOpenBuildingsCSV(), what: 'Open Buildings outline + 2.5D height' },
  { key: 'osm', file: 'osm-overpass.json', kind: 'json', make: () => json(SM.sampleOsmJSON()), what: 'OpenStreetMap buildings and roads' },
  { key: 'irradiance', file: 'irradiance-nasa-power.json', kind: 'json', make: () => json({ ghiKWhPerDay: 5.35, source: 'Bengaluru long-term mean (NASA POWER)' }), what: 'Daily solar irradiance' },
  { key: 'dxf', file: 'main-block-MB-1.dxf', kind: 'text', make: () => SM.sampleDXF(), what: 'CAD floor plan, first floor', meta: { floor: 'MB-1' } },
  { key: 'ifc', file: 'main-block.ifc', kind: 'text', make: () => SM.sampleIFC(), what: 'BIM model spaces' },
  { key: 'plan', file: 'scanned-plan-MB-G.json', kind: 'json', make: () => json(SM.samplePlanRecognition()), what: 'Scanned ground-floor plan, segmentation + OCR', meta: { floor: 'MB-G' } },
  { key: 'sld', file: 'single-line-diagram-ocr.txt', kind: 'text', make: () => SM.sampleSLDText(), what: 'Single-line diagram OCR text' },
  { key: 'roomplan', file: 'roomplan-walkthrough.json', kind: 'json', make: () => json(SM.sampleRoomPlan()), what: 'Phone walkthrough (Apple RoomPlan)' },
  { key: 'nameplates', file: 'nameplates-ocr.json', kind: 'json', make: () => json(SM.sampleNameplates()), what: 'Equipment nameplate photos, OCR text' },
  { key: 'cctvCounts', file: 'cctv-people-counts.json', kind: 'json', make: () => json(SM.sampleCctvCounts()), what: 'SEE engine people counts per camera' },
  { key: 'meter', file: 'block-meter-1min.csv', kind: 'text', make: () => SM.sampleMeterCSV(), what: 'Main Block energy meter, 1-min kW' },
  { key: 'wifi', file: 'wifi-ap-clients.csv', kind: 'text', make: () => SM.sampleWifiCSV(), what: 'Wi-Fi access point client counts' },
  { key: 'timetable', file: 'timetable-bookings.csv', kind: 'text', make: () => SM.sampleTimetableCSV(), what: 'Timetable and lab bookings' },
];
const manifest = { building: 'NHCE Main Block', note: 'Generated by tools/make-test-files.mjs from js/scan/samples.js. Six real-world problems are planted.', files: [] };
for (const f of FILES) {
  const body = f.make();
  writeFileSync(new URL(f.file, OUT), body);
  manifest.files.push({ key: f.key, file: f.file, kind: f.kind, what: f.what, bytes: Buffer.byteLength(body), ...(f.meta ? { meta: f.meta } : {}) });
}
writeFileSync(new URL('manifest.json', OUT), json(manifest));
console.log(`wrote ${FILES.length} files + manifest.json to test-files/`);
